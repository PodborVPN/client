package podbor.screen

/**
 * Что экран спросил у человека и ждёт ответа: своя шторка или окно системы. Пока вопрос открыт, возврат на экран — не
 * новое открытие, а пересозданный экран вопрос не повторяет: ответ придёт ему.
 */
enum class Ask {
    /** Шторка «Зачем Podbor геолокация» — до системного запроса разрешений. */
    Disclosure,
    Permissions,
    VpnConsent,
    /** Выбор «куда отправить» Ленту. */
    Chooser,
    Qr,
    /** Шторка «включи постоянный VPN» — раз за установку, когда VPN впервые заработал. */
    AlwaysOn,
}

/**
 * Чего экран ждёт после открытия в [Open.atMs]/[Line.atMs]: на главном — сессию и замер сети на ней, на странице
 * подписки — плашку сети без VPN. Каждое открытие — новое значение: оно сменяет недоделанное прежнее.
 */
sealed interface Want {
    data object Idle : Want
    data class Open(val atMs: Long) : Want
    data class Line(val atMs: Long) : Want
}
