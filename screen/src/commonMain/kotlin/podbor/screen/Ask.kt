package podbor.screen

/**
 * Что экран спросил у человека и ждёт ответа: своя шторка или окно системы. Пока вопрос открыт, возврат на экран — не
 * новое открытие, а пересозданный экран вопрос не повторяет: ответ придёт ему.
 */
enum class Ask {
    /** Шторка «Зачем Podbor геолокация» — до системного запроса разрешений. */
    Disclosure,
    Permissions,
    VpnConsent,
    /** Выбор «куда отправить» Ленту. */
    Chooser,
    Qr,
}
